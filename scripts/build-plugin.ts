// `npm run build:plugin` (04 §9): bundles the client into plugins/claude-code/dist/pairwire.mjs
// and generates the skill from specs/06-agent-guide.md section 2. The output is committed, and
// CI fails when it differs from a fresh build, so it must be deterministic.
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = fileURLToPath(new URL("..", import.meta.url));
const plugin = join(root, "plugins/claude-code");

/** The fenced ````markdown block of 06 §2 is SKILL.md verbatim (06 §1). */
export function extractSkill(guide: string): string {
  const section = guide.slice(guide.indexOf("## 2. SKILL.md"));
  const m = section.match(/````markdown\n([\s\S]*?)\n````/);
  if (!m) throw new Error("06-agent-guide.md: no ````markdown block in section 2");
  return m[1]! + "\n";
}

/** The package directory of a bundled input path, e.g. node_modules/@scope/name/x.js -> node_modules/@scope/name. */
function packageDir(input: string): string | null {
  const parts = input.split("/");
  const at = parts.lastIndexOf("node_modules");
  if (at < 0) return null;
  const scoped = parts[at + 1]?.startsWith("@");
  return parts.slice(0, at + (scoped ? 3 : 2)).join("/");
}

const LICENSE_FILES = ["LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "license", "LICENSE-MIT"];

/**
 * The licenses of every third-party package esbuild put into the bundle (their MIT/ISC terms
 * require shipping the notice). Sorted, so the output is deterministic.
 */
export function thirdPartyNotices(inputs: readonly string[]): string {
  const dirs = [...new Set(inputs.map(packageDir).filter((d): d is string => d !== null))];
  const pkgs = dirs
    .map((dir) => {
      const pkg = JSON.parse(readFileSync(join(root, dir, "package.json"), "utf8")) as { name: string; version: string; license?: string };
      const file = LICENSE_FILES.find((f) => existsSync(join(root, dir, f)));
      if (!file) throw new Error(`${pkg.name}: no license file to include in THIRD_PARTY_NOTICES.md`);
      return { ...pkg, text: readFileSync(join(root, dir, file), "utf8").trim() };
    })
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
  const unique = pkgs.filter((p, i) => i === 0 || p.name !== pkgs[i - 1]!.name || p.version !== pkgs[i - 1]!.version);
  return [
    "# Third-party notices",
    "",
    "pairwire's bundle (dist/) includes code from these packages, under their licenses below.",
    "Generated by npm run build:plugin.",
    ...unique.flatMap((p) => ["", `## ${p.name} ${p.version} (${p.license ?? "see license"})`, "", "```", p.text, "```"]),
    "",
  ].join("\n");
}

async function main(): Promise<void> {
  rmSync(join(plugin, "dist"), { recursive: true, force: true });
  const result = await build({
    entryPoints: { pairwire: join(root, "packages/client/src/main.ts") },
    outdir: join(plugin, "dist"),
    outExtension: { ".js": ".mjs" },
    // Each subcommand is its own chunk (main.ts imports them lazily), so hooks skip the MCP SDK.
    splitting: true,
    chunkNames: "chunks/[name]-[hash]",
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node20",
    conditions: ["source"],
    // ws loads these optional native helpers in a try/catch.
    external: ["bufferutil", "utf-8-validate"],
    // Bundled CommonJS (ws, ajv) calls require() for Node built-ins.
    banner: { js: 'import { createRequire as __pwCreateRequire } from "node:module";\nconst require = __pwCreateRequire(import.meta.url);' },
    legalComments: "eof",
    logLevel: "warning",
    metafile: true,
  });
  writeFileSync(join(plugin, "THIRD_PARTY_NOTICES.md"), thirdPartyNotices(Object.keys(result.metafile.inputs)));
  const skill = extractSkill(readFileSync(join(root, "specs/06-agent-guide.md"), "utf8"));
  mkdirSync(join(plugin, "skills/pairwire"), { recursive: true });
  writeFileSync(
    join(plugin, "skills/pairwire/SKILL.md"),
    skill.replace(/^(---\n[\s\S]*?\n---\n)/, "$1\n<!-- Generated from specs/06-agent-guide.md section 2 by npm run build:plugin. Do not edit. -->\n"),
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
